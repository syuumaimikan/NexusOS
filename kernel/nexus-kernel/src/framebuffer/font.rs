//! An 8x8 bitmap font covering printable ASCII.
//!
//! Bitmapped rather than vector because the kernel has no floating point, no
//! rasteriser and no font files: this is the console and panic-screen face, and
//! it has to work before anything else does. Real typography arrives with
//! NexusUI, in user space, where a text shaper can be afforded.
//!
//! Each glyph is eight bytes, one per row, most significant bit leftmost. The
//! renderer scales by whole integers, so the same data serves a small status
//! line and a large title without any resampling blur.

/// First character the font covers.
pub const FIRST_CHARACTER: u8 = 0x20;
/// Last character the font covers.
pub const LAST_CHARACTER: u8 = 0x7E;

/// Width of a glyph in pixels.
pub const GLYPH_WIDTH: u32 = 8;
/// Height of a glyph in pixels.
pub const GLYPH_HEIGHT: u32 = 8;

