//! Glyphs.
//!
//! Two tiers, because the kernel has to render text before it can be sure of
//! having a font:
//!
//! * a **built-in** 8x8 ASCII face, compiled into the source below. It always
//!   works, needs no tooling, and is what the panic screen falls back to.
//! * a **generated** face covering exactly the characters the locale files use,
//!   including CJK, rasterised at build time from a font installed on the build
//!   machine. See `build.rs` for why it is generated rather than committed.
//!
//! Both are presented through one [`Glyph`] type on a 16-pixel cell, so the
//! text renderer never has to know which tier answered. The built-in 8x8 glyphs
//! are centred vertically in that cell, which keeps their baseline consistent
//! with generated ones when the two are mixed.
//!
//! Advance width is per glyph: 8 pixels for Latin and 16 for CJK, the correct
//! rule for the scripts NexusOS renders today. That is what lets a Japanese
//! label and an English one occupy sensible, different widths instead of being
//! forced into the same grid.

