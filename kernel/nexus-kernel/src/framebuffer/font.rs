/// Generated glyphs: GLYPH_COUNT, CODEPOINTS, WIDTHS, GLYPHS.
mod generated {
    include!(concat!(env!("OUT_DIR"), "/wide_font.rs"));
}

/// Height of a glyph cell, in pixels.
pub const CELL_HEIGHT: u32 = 16;

/// Advance width of a half-width glyph, in pixels.
pub const HALF_WIDTH: u32 = 8;
/// Advance width of a full-width glyph, in pixels.
pub const FULL_WIDTH: u32 = 16;

/// A glyph ready to draw: sixteen rows, most significant bit leftmost.
#[derive(Clone, Copy)]
pub struct Glyph {
    pub rows: [u16; CELL_HEIGHT as usize],
    /// How far the cursor moves after drawing, in pixels at scale 1.
    pub advance: u32,
}

/// Drawn when a character has no glyph in either tier.
///
/// A hollow box rather than a blank: missing coverage should be visible, not
/// silently swallowed. This is the same convention every other text stack uses,
/// and for the same reason.
fn missing(advance: u32) -> Glyph {
    let mut rows = [0u16; CELL_HEIGHT as usize];
    let right_edge = if advance == HALF_WIDTH {
        0x0100
    } else {
        0x0001
    };
    let full = if advance == HALF_WIDTH {
        0xFF00
    } else {
        0xFFFF
    };

    rows[2] = full;
    rows[13] = full;
    let mut row = 3;
    while row < 13 {
        rows[row] = 0x8000 | right_edge;
        row += 1;
    }
    Glyph { rows, advance }
}

/// Widen a built-in 8x8 bitmap into the 16-pixel cell.
///
/// Centred vertically so its baseline lines up with generated glyphs when both
/// appear on one line.
fn from_builtin(bitmap: &[u8; 8]) -> Glyph {
    const TOP: usize = (CELL_HEIGHT as usize - 8) / 2;

    let mut rows = [0u16; CELL_HEIGHT as usize];
    let mut index = 0;
    while index < 8 {
        rows[TOP + index] = (bitmap[index] as u16) << 8;
        index += 1;
    }
    Glyph {
        rows,
        advance: HALF_WIDTH,
    }
}

/// The glyph for `character`.
///
/// The generated face is consulted first because it covers more and is drawn at
/// the cell's full resolution; the built-in face answers for ASCII when no
/// generated face was produced.
#[must_use]
pub fn glyph(character: char) -> Glyph {
    let codepoint = character as u32;

    if let Ok(index) = generated::CODEPOINTS.binary_search(&codepoint) {
        return Glyph {
            rows: generated::GLYPHS[index],
            advance: u32::from(generated::WIDTHS[index]),
        };
    }

    let byte = codepoint as u8;
    if codepoint < 0x80 && (FIRST_CHARACTER..=LAST_CHARACTER).contains(&byte) {
        return from_builtin(&BUILTIN[(byte - FIRST_CHARACTER) as usize]);
    }

    missing(if codepoint < 0x80 {
        HALF_WIDTH
    } else {
        FULL_WIDTH
    })
}

/// Total advance width of `text`, in pixels at scale 1.
#[must_use]
pub fn measure(text: &str) -> u32 {
    text.chars().map(|character| glyph(character).advance).sum()
}

/// Whether the generated face was available at build time.
///
/// Reported at boot so that "the Japanese labels are boxes" is immediately
/// traceable to a build that could not rasterise, rather than to a bug in the
/// renderer.
#[must_use]
pub fn has_generated_face() -> bool {
    generated::GLYPH_COUNT > 0
}

/// Number of glyphs in the generated face.
#[must_use]
pub fn generated_glyph_count() -> usize {
    generated::GLYPH_COUNT
}

// The kernel binary has no host test harness -- it is `no_main` with its own
// panic handler -- so what can be checked here is checked at compile time
// instead of in tests that would never run. Rendering itself is verified by
// booting and capturing the screen; see scripts/screenshot.ps1.

/// The table must cover exactly the range the lookup indexes into, or `glyph`
/// would read past the end for the last few characters.
const _: () = assert!(BUILTIN.len() == (LAST_CHARACTER - FIRST_CHARACTER + 1) as usize);

/// Space must be blank and a few representative glyphs must not be, which
/// catches a table accidentally truncated or shifted by an entry.
const _: () = {
    let space = BUILTIN[(b' ' - FIRST_CHARACTER) as usize];
    let mut index = 0;
    while index < 8 {
        assert!(space[index] == 0, "space must be blank");
        index += 1;
    }
};

/// A shifted table is the likeliest mistake, and it shows up as the wrong glyph
/// at a known index rather than as a missing one. These pin three widely
/// separated entries to their expected first row.
const _: () = {
    assert!(BUILTIN[(b'A' - FIRST_CHARACTER) as usize][0] == 0x38);
    assert!(BUILTIN[(b'0' - FIRST_CHARACTER) as usize][0] == 0x7C);
    assert!(BUILTIN[(b'~' - FIRST_CHARACTER) as usize][0] == 0x76);
};
